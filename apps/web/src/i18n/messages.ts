export const WEB_MESSAGES: Readonly<Record<ResolvedAppLocale, WebMessages>> = {
  en: EN_MESSAGES,
  "zh-CN": ZH_CN_MESSAGES,
};

export function translateWebMessage(
  locale: ResolvedAppLocale,
  key: WebMessageKey,
  values?: WebMessageValues,
): string {
  const message = WEB_MESSAGES[locale][key];
  if (!values) return message;

  return message.replace(/\{([A-Za-z][A-Za-z0-9]*)\}/g, (placeholder, name: string) => {
    const value = values[name];
    return value === undefined ? placeholder : String(value);
  });
}
